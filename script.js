// === INTERACTIVE HOME OFFICE ===
(function setupInteractiveHomeOffice() {
 const word = document.getElementById("personalWorldWord");
 const copy = document.getElementById("personalWorldCopy");
 const index = document.getElementById("personalWorldIndex");
 const hotspotButtons = Array.from(document.querySelectorAll(".office-hotspot"));
 const topicButtons = Array.from(document.querySelectorAll(".personal-topic-btn"));

 if (!word || !copy || !index || (!hotspotButtons.length && !topicButtons.length)) return;

 const items = [
  ["draw", "personalDrawWord", "personalDrawCopy"],
  ["game", "personalGameWord", "personalGameCopy"],
  ["code", "personalCodeWord", "personalCodeCopy"],
  ["read", "personalReadWord", "personalReadCopy"],
  ["interior", "personalInteriorWord", "personalInteriorCopy"]
 ];

 let active = "draw";

 function lang() {
  return localStorage.getItem("linnalice-lang") || "sv";
 }

 function renderButtons() {
  const dict = translations[lang()];
  [...hotspotButtons, ...topicButtons].forEach((button) => {
   const fact = button.dataset.fact;
   const item = items.find(([id]) => id === fact);
   if (!item) return;
   const [, wordKey] = item;
   const label = dict[wordKey];
   button.setAttribute("aria-label", label);
   button.dataset.label = label;
   if (button.matches(".personal-topic-btn")) button.textContent = label;
  });
 }

 function showFact(fact, animate = true) {
  if (!items.some(([id]) => id === fact)) return;
  active = fact;
  const dict = translations[lang()];
  const activeIndex = items.findIndex(([id]) => id === active);
  const [, wordKey, copyKey] = items[activeIndex];

  if (animate) {
   word.classList.remove("personal-swap");
   copy.classList.remove("personal-swap");
   void word.offsetWidth;
  }

  word.textContent = dict[wordKey];
  copy.textContent = dict[copyKey];
  index.textContent = `${String(activeIndex + 1).padStart(2, "0")} / ${String(items.length).padStart(2, "0")}`;

  hotspotButtons.forEach((button) => button.classList.toggle("is-active", button.dataset.fact === active));
  topicButtons.forEach((button) => button.classList.toggle("is-active", button.dataset.fact === active));

  if (animate) {
   word.classList.add("personal-swap");
   copy.classList.add("personal-swap");
  }
 }

 hotspotButtons.forEach((button) => {
  button.addEventListener("mouseenter", () => showFact(button.dataset.fact));
  button.addEventListener("focus", () => showFact(button.dataset.fact));
  button.addEventListener("click", () => showFact(button.dataset.fact));
 });

 topicButtons.forEach((button) => {
  button.addEventListener("mouseenter", () => showFact(button.dataset.fact));
  button.addEventListener("focus", () => showFact(button.dataset.fact));
  button.addEventListener("click", () => showFact(button.dataset.fact));
 });

 document.getElementById("languageToggle")?.addEventListener("click", () => {
  setTimeout(() => {
   renderButtons();
   showFact(active, false);
  }, 0);
 });

 renderButtons();
 showFact(active, false);
})();


