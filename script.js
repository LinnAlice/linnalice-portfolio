const languageToggle = document.getElementById("languageToggle");
const languageLabel = document.getElementById("languageLabel");
const themeToggle = document.getElementById("themeToggle");
const year = document.getElementById("year");

function currentLang() {
 return localStorage.getItem("linnalice-lang") || "sv";
}

function setLanguage(lang) {
 const dict = translations[lang];
 document.documentElement.lang = lang;
 document.querySelectorAll("[data-i18n]").forEach((el) => {
  const key = el.dataset.i18n;
  if (dict[key]) el.textContent = dict[key];
 });

 if (languageLabel) languageLabel.textContent = lang === "sv" ? "EN" : "SV";
 if (languageToggle) languageToggle.setAttribute("aria-label", lang === "sv" ? "Byt till engelska" : "Switch to Swedish");
 const mobileMenuButton = document.querySelector(".mobile-menu-btn");
 if (mobileMenuButton) mobileMenuButton.setAttribute("aria-label", lang === "sv" ? "Öppna meny" : "Open menu");
 localStorage.setItem("linnalice-lang", lang);
}

if (languageToggle) {
 languageToggle.addEventListener("click", () => {
  setLanguage(currentLang() === "sv" ? "en" : "sv");
 });
}

if (themeToggle) {
 themeToggle.addEventListener("click", () => {
  const current = document.documentElement.dataset.theme || "dark";
  const next = current === "dark" ? "light" : "dark";
  document.documentElement.dataset.theme = next;
      localStorage.setItem("linnalice-theme", next);
    themeToggle.setAttribute("aria-label", next === "dark" ? "Switch to light mode" : "Switch to dark mode");
 });
}

function createFireflies() {
 const container = document.getElementById("fireflies");
 if (!container) return;

 const count = window.matchMedia("(max-width: 680px)").matches ? 18 : 30;

 for (let i = 0; i < count; i++) {
  const f = document.createElement("span");
  f.className = "firefly";

  const size = (Math.random() * 3.2 + 2.2).toFixed(1) + "px";
  const x = (Math.random() * 96 + 2).toFixed(1) + "%";
  const y = (Math.random() * 82 + 8).toFixed(1) + "%";
  const dx = (Math.random() * 70 - 35).toFixed(0) + "px";
  const dy = (Math.random() * 70 - 35).toFixed(0) + "px";
  const drift = (Math.random() * 9 + 10).toFixed(1) + "s";
  const blink = (Math.random() * 3 + 3).toFixed(1) + "s";
  const delay = (Math.random() * -10).toFixed(1) + "s";

  f.style.setProperty("--size", size);
  f.style.setProperty("--x", x);
  f.style.setProperty("--y", y);
  f.style.setProperty("--dx", dx);
  f.style.setProperty("--dy", dy);
  f.style.setProperty("--drift", drift);
  f.style.setProperty("--blink", blink);
  f.style.setProperty("--delay", delay);

  container.appendChild(f);
 }
}

